//! Protobuf definitions and gRPC code for the schedr master <-> worker agent protocol.
//!
//! The messages are generated from `proto/schedr/protocol/v1/master.proto` into [`pb`]; this
//! crate adds the protocol version check and the conversions to and from `schedr-model`.

pub mod convert;
pub mod version;

#[cfg(test)]
mod tests;

/// The generated messages and the `Master` service (client and server).
#[allow(
    missing_docs,
    clippy::all,
    clippy::pedantic,
    reason = "generated by tonic-prost-build from master.proto"
)]
pub mod pb {
    tonic::include_proto!("schedr.protocol.v1");
}

pub use convert::{ConversionError, RejectReaction, reject_reaction};
pub use version::{PROTOCOL_VERSION, VersionMismatch, check_worker_version};
