#!/usr/bin/env python3
"""The decisions: one TOML file per decision in `decisions/`, and `DECISIONS.md` generated.

A decision's file is `decisions/D<n>.toml`:

    title = "TriggerDagOperator gives the target run's ID"
    date = 2026-11-08
    by = "user"                 # user, claude
    status = "active"           # active, superseded, dropped, untraced
    superseded_by = 0           # the decision replacing it (status "superseded" only)
    topic = "chained-runs"      # a topic of design/README.md
    summary = '''
    What holds, in two to four lines: the result, not the reasons.
    '''
    history = "PROJECT.md: Dependencies between DAGs"   # where its reasons are
    step = "M4.12a"             # optional: the step that built it
    code = ["crates/schedr-master/src/chained.rs"]      # optional: where it lives
    checked = 2026-11-09        # optional: when a second reader compared it with the full text

`untraced` is a number with no text found (skipped, or decided without being written down); its
summary says what is known. `decisions/next-id` holds the next free number. Every number below
it has a file, and every "decision N" written in the repository is below it.

Usage:
    python3 scripts/decisions.py render          # write DECISIONS.md
    python3 scripts/decisions.py check           # validate; fail if DECISIONS.md is stale
    python3 scripts/decisions.py new "<title>"   # a new decision's file; prints its path
"""

from __future__ import annotations

import datetime
import json
import re
import subprocess
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FOLDER = ROOT / "decisions"
OUTPUT = ROOT / "DECISIONS.md"
TOPICS = ROOT / "design" / "README.md"
BY = ("user", "claude")
STATUS = ("active", "superseded", "dropped", "untraced")
REQUIRED = {"title", "date", "by", "status", "topic", "summary", "history"}
OPTIONAL = {"superseded_by", "step", "code", "checked"}
NAME = re.compile(r"D([1-9][0-9]*)\.toml")
TOPIC_ROW = re.compile(r"^\| `([a-z0-9-]+)` \|", re.MULTILINE)
# "decision 12", "decisions 326-333", "decisions 87, 88 and 90"; a year (2026) isn't one.
DASH = "[-\u2013]"  # a hyphen or an en dash
MENTION = re.compile(rf"[Dd]ecisions? ((?:\d+[A-Za-z']*(?:\s*{DASH}\s*\d+)?(?:,\s*|\s+and\s+)?)+)")
PART = re.compile(rf"(\d+)[A-Za-z']*(?:\s*{DASH}\s*(\d+))?")
# A range wider than this is a typo or two numbers, not a list of decisions.
WIDEST_RANGE = 40
# From here a number is a year ("decision 2026" in a date), not a decision.
FIRST_YEAR = 1900
OWN_FILES = ("decisions.py", "test_decisions.py")
# What the mention check reads: text the project writes (not generated files nor history).
SKIPPED = ("target/", "site/", "docs/_generated/", "history/", "decisions/", "DECISIONS.md")
SUFFIXES = (".md", ".rs", ".py", ".toml", ".sql", ".proto", ".yml", ".yaml", ".sh", ".html")
# A file the mention check can't read is skipped (a tuple: older Pythons run this script).
UNREADABLE = (OSError, UnicodeDecodeError)
GENERATED = (
    "<!-- Generated by `scripts/decisions.py render` from decisions/: edit the files there. -->\n"
)


class DecisionError(Exception):
    """A decision's file, or a mention, that doesn't follow the rules."""


@dataclass(frozen=True)
class Decision:
    """One decision, as its file says."""

    number: int
    title: str
    date: datetime.date
    by: str
    status: str
    superseded_by: int
    topic: str
    summary: str
    history: str
    step: str
    code: tuple[str, ...]
    checked: datetime.date | None = None

    @property
    def id(self) -> str:
        """`D357`."""
        return f"D{self.number}"

    @property
    def shown_status(self) -> str:
        """The status, with what replaced it."""
        if self.status == "superseded":
            return f"superseded by D{self.superseded_by}"
        return self.status


def topics(path: Path = TOPICS) -> set[str]:
    """The topics `design/README.md` lists."""
    return set(TOPIC_ROW.findall(path.read_text()))


def read(path: Path, known_topics: set[str]) -> Decision:
    """A decision's file, checked."""
    name = NAME.fullmatch(path.name)
    if name is None:
        raise DecisionError(f"{path.name}: a decision's file is named `D<number>.toml`")
    try:
        data = tomllib.loads(path.read_text())
    except tomllib.TOMLDecodeError as error:
        raise DecisionError(f"{path.name}: {error}") from error
    missing, extra = sorted(REQUIRED - set(data)), sorted(set(data) - REQUIRED - OPTIONAL)
    if missing or extra:
        raise DecisionError(f"{path.name}: missing {missing}, unknown {extra}")
    for field in ("title", "summary", "history"):
        if not isinstance(data[field], str) or not data[field].strip():
            raise DecisionError(f"{path.name}: `{field}` is a non-empty string")
    if not isinstance(data["date"], datetime.date) or isinstance(data["date"], datetime.datetime):
        raise DecisionError(f"{path.name}: `date` is a date, e.g. 2026-11-08 (no quotes)")
    if data["by"] not in BY:
        raise DecisionError(f"{path.name}: `by` is one of {', '.join(BY)}")
    if data["status"] not in STATUS:
        raise DecisionError(f"{path.name}: `status` is one of {', '.join(STATUS)}")
    superseded_by = data.get("superseded_by", 0)
    if not isinstance(superseded_by, int) or isinstance(superseded_by, bool):
        raise DecisionError(f"{path.name}: `superseded_by` is a decision's number")
    if (data["status"] == "superseded") != (superseded_by > 0):
        raise DecisionError(
            f"{path.name}: `superseded_by` is given exactly when the status is `superseded`"
        )
    if data["topic"] not in known_topics:
        raise DecisionError(
            f"{path.name}: topic `{data['topic']}` isn't one of design/README.md's topics"
        )
    step, code = optional_fields(path.name, data)
    checked = data.get("checked")
    if checked is not None and (
        not isinstance(checked, datetime.date) or isinstance(checked, datetime.datetime)
    ):
        raise DecisionError(f"{path.name}: `checked` is a date, e.g. 2026-11-09 (no quotes)")
    return Decision(
        number=int(name[1]),
        title=data["title"].strip(),
        date=data["date"],
        by=data["by"],
        status=data["status"],
        superseded_by=superseded_by,
        topic=data["topic"],
        summary=" ".join(data["summary"].split()),
        history=data["history"].strip(),
        step=step.strip(),
        code=tuple(code),
        checked=checked,
    )


def optional_fields(name: str, data: dict[str, object]) -> tuple[str, list[str]]:
    """`step` and `code`, checked; empty when not given."""
    step = data.get("step", "")
    code = data.get("code", [])
    if not isinstance(step, str):
        raise DecisionError(f'{name}: `step` is a string, e.g. "M4.12a"')
    if not isinstance(code, list) or not all(isinstance(c, str) and c for c in code):
        raise DecisionError(f"{name}: `code` is a list of paths")
    return step, [str(c) for c in code]


def next_number(folder: Path) -> int:
    """The next free number, from `next-id` (`D367`)."""
    text = (folder / "next-id").read_text().strip()
    if not re.fullmatch(r"D[1-9][0-9]*", text):
        raise DecisionError(f"next-id: `{text}` isn't a decision ID like D367")
    return int(text[1:])


def load(folder: Path, known_topics: set[str]) -> list[Decision]:
    """Every decision in `folder`, by number; checked against `next-id` and each other."""
    decisions = sorted(
        (read(path, known_topics) for path in folder.glob("*.toml")), key=lambda d: d.number
    )
    stray = sorted(
        p.name
        for p in folder.iterdir()
        if p.name not in {"README.md", "next-id"} and not p.name.endswith(".toml")
    )
    if stray:
        raise DecisionError(f"not a decision's file: {', '.join(stray)}")
    upto = next_number(folder)
    numbers = {d.number for d in decisions}
    gaps = [n for n in range(1, upto) if n not in numbers]
    if gaps:
        shown = ", ".join(f"D{n}" for n in gaps[:10])
        raise DecisionError(f"no file for {shown}: a number not used gets status `untraced`")
    if decisions and decisions[-1].number >= upto:
        raise DecisionError(f"next-id says D{upto}, but {decisions[-1].id} exists")
    for decision in decisions:
        if decision.status == "superseded" and decision.superseded_by not in numbers:
            raise DecisionError(f"{decision.id}: superseded by D{decision.superseded_by}, unknown")
        if decision.superseded_by == decision.number:
            raise DecisionError(f"{decision.id}: can't supersede itself")
    return decisions


def missing_code(decisions: list[Decision], root: Path) -> list[str]:
    """`code` paths of active decisions that don't exist."""
    return [
        f"{d.id}: {path}"
        for d in decisions
        if d.status == "active"
        for path in d.code
        if not (root / path).exists()
    ]


def mentions(text: str) -> set[int]:
    """The decision numbers `text` names ("decision 12", "decisions 3-5")."""
    found: set[int] = set()
    for match in MENTION.finditer(text):
        for part in PART.finditer(match.group(1)):
            first = int(part.group(1))
            last = int(part.group(2)) if part.group(2) else first
            # A year or a wide range isn't a list of decisions.
            if last < first or last - first > WIDEST_RANGE:
                last = first
            found.update(range(first, last + 1))
    return found


def tracked(root: Path) -> list[Path]:
    """The repository's tracked text files the mention check reads."""
    listed = subprocess.run(
        ["git", "ls-files"], cwd=root, capture_output=True, text=True, check=True
    ).stdout.split()
    return [
        root / name
        for name in listed
        if name.endswith(SUFFIXES)
        and not name.startswith(SKIPPED)
        # The script and its tests name decisions as examples.
        and Path(name).name not in OWN_FILES
    ]


def unknown_mentions(files: list[Path], upto: int) -> list[str]:
    """Mentions of a decision with no file yet (at or past `next-id`); years aside."""
    found: list[str] = []
    for path in files:
        try:
            text = path.read_text(encoding="utf-8")
        except UNREADABLE:
            continue
        found.extend(
            f"{path.name}: decision {n}" for n in sorted(mentions(text)) if upto <= n < FIRST_YEAR
        )
    return found


def render(folder: Path, known_topics: set[str]) -> str:
    """DECISIONS.md: every decision by number, then the active ones by topic."""
    decisions = load(folder, known_topics)
    parts = [
        GENERATED,
        "# Decisions\n\n",
        "One line per decision; the file `decisions/D<n>.toml` has its summary, and its "
        "`history` says where its reasons are (PROJECT.md). How each topic works now: "
        "`design/<topic>.md`.\n\n",
        "| # | Date | By | Status | Topic | Title |\n|---|---|---|---|---|---|\n",
    ]
    for d in reversed(decisions):
        row = (d.id, d.date.isoformat(), d.by, d.shown_status, d.topic, d.title)
        parts.append("| " + " | ".join(row) + " |\n")
    parts.append("\n## Active, by topic\n")
    for topic in sorted({d.topic for d in decisions}):
        active = [d for d in decisions if d.topic == topic and d.status == "active"]
        if not active:
            continue
        parts.append(f"\n### {topic}\n\n")
        parts.extend(f"- {d.id}: {d.title}\n" for d in reversed(active))
    return "".join(parts)


def new(folder: Path, title: str) -> Path:
    """A new decision's file with the next number, to fill in; `next-id` moves on."""
    number = next_number(folder)
    path = folder / f"D{number}.toml"
    path.write_text(
        f"title = {json.dumps(title, ensure_ascii=False)}\n"
        f"date = {datetime.date.today().isoformat()}\n"
        'by = "user"  # user, claude\n'
        'status = "active"  # active, superseded, dropped, untraced\n'
        'topic = ""  # a topic of design/README.md\n'
        "summary = '''\n'''\n"
        'history = "PROJECT.md: Journal, ' + datetime.date.today().isoformat() + '"\n'
        'step = ""\n'
        "code = []\n"
    )
    (folder / "next-id").write_text(f"D{number + 1}\n")
    return path


def main(argv: list[str]) -> int:
    """`render`, `check` or `new <title>`."""
    try:
        known = topics()
        if argv[1:] == ["render"]:
            OUTPUT.write_text(render(FOLDER, known))
            return 0
        if argv[1:] == ["check"]:
            decisions = load(FOLDER, known)
            problems = missing_code(decisions, ROOT)
            problems += unknown_mentions(tracked(ROOT), next_number(FOLDER))
            if problems:
                raise DecisionError("\n  ".join(["decisions:", *problems]))
            if not OUTPUT.exists() or OUTPUT.read_text() != render(FOLDER, known):
                raise DecisionError(
                    "DECISIONS.md is out of date: run `make decisions` (python3 "
                    "scripts/decisions.py render)"
                )
            return 0
        if argv[1:2] == ["new"] and len(argv[2:]) == 1 and argv[2].strip():
            print(new(FOLDER, argv[2].strip()).relative_to(ROOT))
            return 0
    except DecisionError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    print(__doc__.split("Usage:")[1], file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
