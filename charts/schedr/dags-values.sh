#!/usr/bin/env bash
# Prints chart values carrying a folder's DAG files, for the chart's `dags.files` (a
# ConfigMap mounted as the DAG root `files`). Part of deploying, not of schedr: it needs only
# bash (3.2 on) and the usual tools (find, sort, wc, base64), GNU or BSD (macOS).
#
#   charts/schedr/dags-values.sh dags/ > dags-values.yaml
#   helm upgrade --install schedr charts/schedr -f my-values.yaml -f dags-values.yaml
#
# The folder's *.py files and its .schedrignore (so its ignore rules hold in the cluster too,
# e.g. for tests), hidden files left out. Flat: a folder with Python files in a subfolder is
# refused (packages go through git-sync), since a ConfigMap's files can be put in subfolders
# only by the pod's spec, which would restart schedr whenever a file is added. __pycache__
# and hidden folders (.git, .venv, ...) are left out. Contents are base64, so no file can
# break the YAML; the output is sorted by name, so the same folder always gives the same
# values. A changed ConfigMap reaches the pod within about a minute, without restarting
# schedr.
set -euo pipefail

# A ConfigMap holds 1 MiB, and so does the Secret Helm keeps a release in, whose values and
# manifest each carry the files in base64 (gzipped; measured: 700 KiB of Python made 690 KB):
# 512 KiB leaves room for files that compress less.
LIMIT=$((512 * 1024))

fail() { echo "dags-values.sh: $*" >&2; exit 1; }

[ $# -eq 1 ] || fail "usage: dags-values.sh <folder>"
folder=${1%/}
[ -d "$folder" ] || fail "\`$folder\` isn't a folder"

# -L: a linked file counts as the file it links to, a linked folder as a folder.
nested=$(cd "$folder" && find -L . \( -name '.?*' -o -name __pycache__ \) -type d -prune \
    -o -path './*/*' -type f -name '*.py' -print | head -n 1)
[ -z "$nested" ] \
    || fail "\`${nested#./}\` is in a subfolder: the folder must be flat (packages go through git-sync, gitSync)"
files=()
while IFS= read -r -d '' file; do
    files+=("${file#./}")
done < <(cd "$folder" && find -L . -mindepth 1 -maxdepth 1 -type f \
    \( \( -name '*.py' ! -name '.*' \) -o -name .schedrignore \) -print0 | LC_ALL=C sort -z)
dags=0
for name in "${files[@]}"; do [[ $name == *.py ]] && dags=$((dags + 1)); done
[ "$dags" -gt 0 ] || fail "no *.py files in \`$folder\`"

# Everything checked before anything is printed: no half a values file on an error.
total=0
for name in "${files[@]}"; do
    [[ $name =~ ^[-._a-zA-Z0-9]+$ ]] \
        || fail "\`$name\`: a name with characters other than letters, digits, - . and _"
    total=$((total + $(wc -c < "$folder/$name")))
done
[ "$total" -le "$LIMIT" ] \
    || fail "the files are $((total / 1024)) KiB together, over the $((LIMIT / 1024)) KiB a ConfigMap carries here: use git-sync (gitSync)"

echo "# DAG files of $folder, generated by charts/schedr/dags-values.sh: don't edit by hand."
echo "dags:"
echo "  files:"
for name in "${files[@]}"; do
    printf '    "%s": "%s"\n' "$name" "$(base64 < "$folder/$name" | tr -d '\n')"
done
