#!/usr/bin/env python3
"""The open bugs: one TOML file per bug in `bugs/`, and `BUGS.md` generated from them.

A bug's file is `bugs/B<n>.toml`:

    title = "a result the master failed to store isn't sent again while the link stays up"
    severity = "high"           # critical, high, medium, low
    probability = "possible"    # likely, possible, rare
    kind = "correctness"        # security, data, correctness, reliability, performance,
                                # usability, tests
    summary = "what happens, and the situation that triggers it"
    found = 2026-10-30
    suspected = false           # found by reasoning, not reproduced yet
    details = '''
    - **Found:** ...
    - **A fix:** ...
    '''

The score is severity (critical 4 ... low 1) times probability (likely 3 ... rare 1), never
written by hand. `bugs/next-id` holds the next free number: a fixed bug's file is deleted, so
the files alone can't say which numbers were used. `BUGS.md` is `bugs/README.md` (the rules),
then the ranking (every security bug first, then by score, severity, probability, newest
first), then the entries, newest first.

Usage:
    python3 scripts/bugs.py render          # write BUGS.md
    python3 scripts/bugs.py check           # validate the files; fail if BUGS.md is stale
    python3 scripts/bugs.py new "<title>"   # a new bug's file, to fill in; prints its path
"""

from __future__ import annotations

import datetime
import json
import re
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FOLDER = ROOT / "bugs"
OUTPUT = ROOT / "BUGS.md"
SEVERITY = {"critical": 4, "high": 3, "medium": 2, "low": 1}
PROBABILITY = {"likely": 3, "possible": 2, "rare": 1}
KINDS = ("security", "data", "correctness", "reliability", "performance", "usability", "tests")
FIELDS = {"title", "severity", "probability", "kind", "summary", "found", "suspected", "details"}
NAME = re.compile(r"B([1-9][0-9]*)\.toml")
GENERATED = "<!-- Generated by `scripts/bugs.py render` from bugs/: edit the files there. -->\n"


class BugError(Exception):
    """A bug's file that doesn't follow the rules."""


@dataclass(frozen=True)
class Bug:
    """One open bug, as its file says."""

    number: int
    title: str
    severity: str
    probability: str
    kind: str
    summary: str
    found: datetime.date
    suspected: bool
    details: str

    @property
    def id(self) -> str:
        """`B58`."""
        return f"B{self.number}"

    @property
    def score(self) -> int:
        """Severity times probability."""
        return SEVERITY[self.severity] * PROBABILITY[self.probability]

    @property
    def heading(self) -> str:
        """The title, marked when the bug is only suspected."""
        return f"{self.title} (Suspected)" if self.suspected else self.title


def read(path: Path) -> Bug:
    """A bug's file, checked."""
    name = NAME.fullmatch(path.name)
    if name is None:
        raise BugError(f"{path.name}: a bug's file is named `B<number>.toml`")
    try:
        data = tomllib.loads(path.read_text())
    except tomllib.TOMLDecodeError as error:
        raise BugError(f"{path.name}: {error}") from error
    if set(data) != FIELDS:
        missing, extra = sorted(FIELDS - set(data)), sorted(set(data) - FIELDS)
        raise BugError(f"{path.name}: missing {missing}, unknown {extra}")
    choices = (("severity", SEVERITY), ("probability", PROBABILITY), ("kind", KINDS))
    for field, allowed in choices:
        if data[field] not in allowed:
            raise BugError(f"{path.name}: `{field}` is one of {', '.join(allowed)}")
    for field in ("title", "summary", "details"):
        if not isinstance(data[field], str) or not data[field].strip():
            raise BugError(f"{path.name}: `{field}` is a non-empty string")
    if not isinstance(data["found"], datetime.date) or isinstance(data["found"], datetime.datetime):
        raise BugError(f"{path.name}: `found` is a date, e.g. 2026-10-30 (no quotes)")
    if not isinstance(data["suspected"], bool):
        raise BugError(f"{path.name}: `suspected` is true or false")
    return Bug(
        number=int(name[1]),
        title=data["title"].strip(),
        severity=data["severity"],
        probability=data["probability"],
        kind=data["kind"],
        summary=data["summary"].strip().rstrip("."),
        found=data["found"],
        suspected=data["suspected"],
        details=data["details"].strip(),
    )


def next_number(folder: Path) -> int:
    """The next free number, from `next-id` (`B89`)."""
    text = (folder / "next-id").read_text().strip()
    if not re.fullmatch(r"B[1-9][0-9]*", text):
        raise BugError(f"next-id: `{text}` isn't a bug ID like B89")
    return int(text[1:])


def load(folder: Path) -> list[Bug]:
    """Every bug in `folder`, newest first; checked against `next-id`."""
    bugs = sorted(
        (read(path) for path in folder.glob("*.toml")), key=lambda b: b.number, reverse=True
    )
    stray = sorted(
        p.name
        for p in folder.iterdir()
        if p.name not in {"README.md", "next-id"} and not p.name.endswith(".toml")
    )
    if stray:
        raise BugError(f"not a bug's file: {', '.join(stray)}")
    if bugs and bugs[0].number >= next_number(folder):
        raise BugError(f"next-id says B{next_number(folder)}, but {bugs[0].id} exists")
    return bugs


def rank(bugs: list[Bug]) -> list[Bug]:
    """The bugs in ranking order.

    Every security bug first (the user, 2026-10-30), then by score, severity, probability,
    newest first.
    """
    return sorted(
        bugs,
        key=lambda b: (
            b.kind != "security",
            -b.score,
            -SEVERITY[b.severity],
            -PROBABILITY[b.probability],
            -b.number,
        ),
    )


def render(folder: Path) -> str:
    """BUGS.md, from the bugs in `folder` and its README."""
    bugs = load(folder)
    parts = [GENERATED, (folder / "README.md").read_text().rstrip(), "\n\n## Ranking\n\n"]
    parts.append("| # | Bug | Score | Severity | Probability | Kind |\n|---|---|---|---|---|---|\n")
    for place, bug in enumerate(rank(bugs), 1):
        kind = "**security**" if bug.kind == "security" else bug.kind
        parts.append(
            f"| {place} | {bug.id}: {bug.heading} | {bug.score} | {bug.severity} | "
            f"{bug.probability} | {kind} |\n"
        )
    for bug in bugs:
        parts.append(
            f"\n## {bug.id}: {bug.heading}\n\n"
            f"- **Rating:** severity **{bug.severity}**, probability **{bug.probability}**, "
            f"{bug.kind} (score {bug.score}): {bug.summary}.\n{bug.details}\n"
        )
    return "".join(parts)


def new(folder: Path, title: str) -> Path:
    """A new bug's file with the next number, its rating to fill in; `next-id` moves on."""
    number = next_number(folder)
    path = folder / f"B{number}.toml"
    path.write_text(
        f"title = {json.dumps(title, ensure_ascii=False)}\n"
        'severity = ""  # critical, high, medium, low\n'
        'probability = ""  # likely, possible, rare\n'
        'kind = ""  # ' + ", ".join(KINDS) + "\n"
        'summary = ""  # what happens, and the situation that triggers it\n'
        f"found = {datetime.date.today().isoformat()}\n"
        "suspected = false\n"
        "details = '''\n- **Found:** \n- **A fix:** \n'''\n"
    )
    (folder / "next-id").write_text(f"B{number + 1}\n")
    return path


def main() -> None:
    """Runs the command named on the command line."""
    command, *rest = sys.argv[1:] or ["help"]
    try:
        if command == "render" and not rest:
            OUTPUT.write_text(render(FOLDER))
        elif command == "check" and not rest:
            if OUTPUT.read_text() != render(FOLDER):
                raise BugError("BUGS.md is out of date: run `python3 scripts/bugs.py render`")
        elif command == "new" and len(rest) == 1:
            print(new(FOLDER, rest[0]).relative_to(ROOT))
        else:
            sys.exit(__doc__)
    except BugError as error:
        sys.exit(f"bugs: {error}")


if __name__ == "__main__":
    main()
